def interpolate(values, output_length):
    x_old = np.linspace(0, 1, len(values))
    x_new = np.linspace(0, 1, output_length)
    return np.interp(x_new, x_old, values)

def create_altitude_profile(total_duration, ceiling):
    climb = 30
    descent = 30
    cruise = total_duration - climb - descent
    altitude = []
    for i in range(climb):
        altitude.append(round(ceiling * i / (climb - 1)))
    altitude.extend([ceiling] * cruise)
    for i in range(descent):
        altitude.append(round(ceiling * (1 - i / (descent - 1))))
    altitude[-1] = 0
    return altitude

def create_flight_path(duration, start_lat, start_long, start_fraction):
    lat_shift = start_lat - LAT_TEMPLATE[0]
    long_shift = start_long - LONG_TEMPLATE[0]
    lat_template = np.array(LAT_TEMPLATE) + lat_shift
    long_template = np.array(LONG_TEMPLATE) + long_shift
    lat_start_index = int(start_fraction * len(lat_template))
    long_start_index = int(start_fraction * len(long_template))
    lat_path = np.concatenate((
        lat_template[lat_start_index:],
        lat_template[:lat_start_index]))
    long_path = np.concatenate((
        long_template[long_start_index:],
        long_template[:long_start_index]))
    return (
        interpolate(lat_path, duration),
        interpolate(long_path, duration))

def make_coordinate_values(start, end, increment):
    from decimal import Decimal
    start = Decimal(str(start))
    end = Decimal(str(end))
    step = Decimal(str(increment))
    if step <= 0:
        raise ValueError("Increment must be positive.")
    direction = Decimal("1") if end >= start else Decimal("-1")
    step *= direction
    values = []
    current = start
    if direction > 0:
        while current <= end:
            values.append(float(current))
            current += step
    else:
        while current >= end:
            values.append(float(current))
            current += step
    return values

def coordinate_label(value, is_latitude):
    if is_latitude:
        hemisphere = "S" if value < 0 else "N"
    else:
        hemisphere = "W" if value < 0 else "E"
    number = f"{abs(value):g}"
    return f"{number}{hemisphere}"

def altitude_label(altitude_ft):
    thousands = altitude_ft / 1000
    number = f"{thousands:g}"
    return f"{number}k"

def generate_csv(filename, start_lat, start_long, ceiling,
                 cruise_duration, start_fraction):
    total_duration = cruise_duration + 60
    latitudes, longitudes = create_flight_path(
        total_duration, start_lat, start_long, start_fraction)
    altitudes = create_altitude_profile(total_duration, ceiling)
    start_time = datetime.now().replace(second=0, microsecond=0)
    with open(filename, "w", newline="", encoding="utf-8") as csvfile:
        writer = csv.writer(csvfile)
        writer.writerow([
            "Time (Zulu)",
            "Latitude",
            "Longitude",
            "Altitude (ft)"])
        for i in range(total_duration):
            writer.writerow([
                (start_time + timedelta(minutes=i)).strftime("%H:%M"),
                round(latitudes[i], 4),
                round(longitudes[i], 4),
                round(altitudes[i])])

